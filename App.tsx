
import React, { useState, useEffect } from 'react';
import { Pet, PetType, Vaccination } from './types';
import Dashboard from './components/Dashboard';
import AIChat from './components/AIChat';
import Login from './components/Login';
import PetSetup from './components/PetSetup';
import PetAITools from './components/PetAITools';
import TrainingTips from './components/TrainingTips';

const App: React.FC = () => {
  const [activeTab, setActiveTab] = useState<'dashboard' | 'chat' | 'vaccines' | 'setup' | 'tools' | 'training' | 'medical'>('dashboard');
  const [newVaxName, setNewVaxName] = useState('');
  const [newVaxDate, setNewVaxDate] = useState('');
  const [newRecordTitle, setNewRecordTitle] = useState('');
  const [newRecordDesc, setNewRecordDesc] = useState('');
  const [newRecordDate, setNewRecordDate] = useState('');
  const [newRecordType, setNewRecordType] = useState<'Checkup' | 'Surgery' | 'Injury' | 'Medication' | 'Other'>('Checkup');
  const [pet, setPet] = useState<Pet | null>(null);
  const [isAuthReady, setIsAuthReady] = useState(false);

  useEffect(() => {
    const loadPet = async () => {
      const savedId = localStorage.getItem('pawpulse_pet_id');
      if (savedId) {
        try {
          const res = await fetch('/api/pets');
          const pets = await res.json();
          const found = pets.find((p: Pet) => p.id === savedId);
          if (found) setPet(found);
        } catch (e) {
          console.error('Failed to load pet from server');
        }
      }
      setIsAuthReady(true);
    };
    loadPet();
  }, []);

  const [loginError, setLoginError] = useState<string | undefined>();

  const calculateDaysLeft = (dueDate: string) => {
    const [day, month, year] = dueDate.split('.');
    const due = new Date(`${year}-${month}-${day}`);
    const now = new Date();
    const diffTime = due.getTime() - now.getTime();
    return Math.ceil(diffTime / (1000 * 60 * 60 * 24));
  };

  const [notifications, setNotifications] = useState<{id: string, message: string, type: 'warning' | 'info'}[]>([]);

  const apiKey = process.env.GEMINI_API_KEY || process.env.API_KEY || "";

  useEffect(() => {
    if (!apiKey) {
      console.error("AI API Key is missing! AI features will not work. Please set GEMINI_API_KEY in your environment.");
    } else {
      console.log("AI API Key detected successfully.");
    }
  }, [apiKey]);

  useEffect(() => {
    if (pet) {
      const upcoming = pet.vaccinations.filter(v => {
        if (v.completedDate) return false;
        const days = calculateDaysLeft(v.dueDate);
        return days >= 0 && days <= 5;
      });

      const newNotifications = upcoming.map(v => ({
        id: `vax-${v.id}`,
        message: `Reminder: ${v.name} is due in ${calculateDaysLeft(v.dueDate)} days!`,
        type: 'warning' as const
      }));

      setNotifications(newNotifications);
    }
  }, [pet?.vaccinations]);

  useEffect(() => {
    if (pet && isAuthReady) {
      localStorage.setItem('pawpulse_pet_id', pet.id);
      // Sync to server
      fetch('/api/pets', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(pet)
      }).catch(e => console.error('Failed to sync pet to server'));
    }
  }, [pet, isAuthReady]);

  // Cleanup effect to remove auto-generated vaccinations if the user wants it vacant
  useEffect(() => {
    if (pet && pet.vaccinations.length > 0) {
      const autoGeneratedPrefixes = ['v-ai-', 'v-baked-', 'v-fallback-', 'v-prebaked-'];
      const specificNamesToRemove = [
        'Annual fecal parasite screening',
        'Inclusion Body Disease (IBD) testing',
        'Respiratory infection health check'
      ];

      const hasAutoGenerated = pet.vaccinations.some(v => 
        (autoGeneratedPrefixes.some(prefix => v.id.startsWith(prefix)) || 
         specificNamesToRemove.includes(v.name)) && !v.completedDate
      );

      if (hasAutoGenerated) {
        const cleanedVaccinations = pet.vaccinations.filter(v => 
          (!autoGeneratedPrefixes.some(prefix => v.id.startsWith(prefix)) && 
           !specificNamesToRemove.includes(v.name)) || v.completedDate
        );
        
        if (cleanedVaccinations.length !== pet.vaccinations.length) {
          handleUpdatePet({
            ...pet,
            vaccinations: cleanedVaccinations
          });
        }
      }
    }
  }, [pet?.id]);

  const handleLogin = async (petData: any) => {
    setLoginError(undefined);
    try {
      const res = await fetch('/api/pets');
      const savedPets = await res.json();
      const existingPet = savedPets.find((p: Pet) => p.name.toLowerCase() === petData.name.toLowerCase());

      if (existingPet) {
        // Check if email and mobile match
        const emailMatch = existingPet.ownerEmail === petData.ownerEmail;
        const mobileMatch = existingPet.ownerMobile === petData.ownerMobile;

        if (emailMatch && mobileMatch) {
          setPet(existingPet);
          setActiveTab('dashboard');
        } else {
          setLoginError('Incorrect email or mobile number for this pet.');
        }
      } else {
        const isFemale = petData.gender === 'Female';
        const newPet: Pet = {
          id: Math.random().toString(36).substr(2, 9),
          name: petData.name,
          ownerEmail: petData.ownerEmail,
          ownerMobile: petData.ownerMobile,
          type: petData.type || PetType.OTHER,
          breed: petData.breed || 'Unknown',
          birthDate: petData.birthDate || new Date().toISOString().split('T')[0],
          age: petData.age || 0,
          gender: petData.gender || 'Male',
          metrics: petData.metrics || [],
          vaccinations: petData.vaccinations || [],
          medicalRecords: [],
          matingEvents: [],
          cycleTracking: isFemale ? {
            history: [],
            isSpayed: false
          } : undefined,
          matingPreferences: isFemale ? {
            lookingForPartner: false
          } : undefined
        };
        setPet(newPet);
        setActiveTab('setup');
      }
    } catch (e) {
      setLoginError('Server connection failed. Please try again.');
    }
  };

  const handleUpdatePet = (updatedPet: Pet) => {
    setPet(updatedPet);
  };

  const handleAddVaccine = (e: React.FormEvent) => {
    e.preventDefault();
    if (!pet || !newVaxName || !newVaxDate) return;
    
    const newVax = {
      id: `v-manual-${Date.now()}`,
      name: newVaxName,
      dueDate: newVaxDate.split('-').reverse().join('.'),
      isRequired: true
    };

    handleUpdatePet({
      ...pet,
      vaccinations: [...pet.vaccinations, newVax]
    });
    setNewVaxName('');
    setNewVaxDate('');
  };

  const handleAddMedicalRecord = (e: React.FormEvent) => {
    e.preventDefault();
    if (!pet || !newRecordTitle || !newRecordDate) return;

    const newRecord = {
      id: `m-record-${Date.now()}`,
      title: newRecordTitle,
      description: newRecordDesc,
      date: newRecordDate,
      type: newRecordType
    };

    handleUpdatePet({
      ...pet,
      medicalRecords: [newRecord, ...(pet.medicalRecords || [])]
    });

    setNewRecordTitle('');
    setNewRecordDesc('');
    setNewRecordDate('');
    setNewRecordType('Checkup');
  };

  const toggleVaccine = (id: string) => {
    if (!pet) return;
    const updatedVaccinations = pet.vaccinations.map(v => 
      v.id === id 
        ? { ...v, completedDate: v.completedDate ? undefined : new Date().toLocaleDateString('en-GB').replace(/\//g, '.') } 
        : v
    );
    setPet({ ...pet, vaccinations: updatedVaccinations });
  };

  const handleLogout = () => {
    localStorage.removeItem('pawpulse_pet_id');
    setPet(null);
    setActiveTab('dashboard');
  };

  const isNeedsSetup = pet && pet.breed === 'Unknown';
  const currentTab = isNeedsSetup ? 'setup' : activeTab;

  const getPetIcon = (type: string, breed?: string) => {
    const b = breed?.toLowerCase() || '';
    if (b.includes('snake')) return 'fa-snake';
    if (b.includes('turtle') || b.includes('tortoise')) return 'fa-turtle';
    if (b.includes('frog')) return 'fa-frog';
    if (b.includes('spider')) return 'fa-spider';
    if (b.includes('horse')) return 'fa-horse';
    if (b.includes('lizard') || b.includes('dragon') || b.includes('gecko')) return 'fa-dragon';
    if (b.includes('pig')) return 'fa-piggy-bank';
    if (b.includes('cow')) return 'fa-cow';
    if (b.includes('bug') || b.includes('insect')) return 'fa-bug';
    if (b.includes('hen') || b.includes('chicken') || b.includes('rooster')) return 'fa-egg';

    switch (type) {
      case 'Dog': return 'fa-dog';
      case 'Cat': return 'fa-cat';
      case 'Bird': return 'fa-dove';
      case 'Rabbit': return 'fa-carrot';
      case 'Hamster': return 'fa-cheese';
      case 'Fish': return 'fa-fish-fins';
      default: return 'fa-paw';
    }
  };

  if (!pet) {
    return <Login onLogin={handleLogin} loginError={loginError} />;
  }

  return (
    <div className="min-h-screen flex flex-col md:flex-row animate-in fade-in duration-700">
      {(!apiKey || apiKey === "undefined") && (
        <div className="fixed top-0 left-0 right-0 bg-rose-600 text-white text-center py-3 z-[100] text-sm font-black flex items-center justify-center gap-3 shadow-lg">
          <i className="fas fa-triangle-exclamation animate-pulse"></i>
          AI SERVICE OFFLINE: Please configure your GEMINI_API_KEY in the Settings menu to enable AI Assistant and Tools.
        </div>
      )}
      <nav className="w-full md:w-64 bg-white border-r border-slate-200 p-6 flex flex-col gap-8 md:fixed md:h-screen z-20">
        <div className="flex items-center gap-2 text-indigo-600">
          <div className="w-10 h-10 bg-indigo-600 text-white rounded-xl flex items-center justify-center">
            <i className="fas fa-paw text-xl"></i>
          </div>
          <span className="text-xl font-bold tracking-tight">PawPulse <span className="text-slate-400 font-light">AI</span></span>
        </div>

        {!isNeedsSetup && (
          <div className="flex-1 flex flex-col gap-1">
            <button onClick={() => setActiveTab('dashboard')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'dashboard' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-columns w-5"></i> Dashboard
            </button>
            <button onClick={() => setActiveTab('chat')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'chat' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-comment-dots w-5"></i> AI Assistant
            </button>
            <button onClick={() => setActiveTab('tools')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'tools' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-wand-magic-sparkles w-5"></i> AI Tools
            </button>
            <button onClick={() => setActiveTab('training')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'training' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-graduation-cap w-5"></i> Training
            </button>
            <button onClick={() => setActiveTab('vaccines')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'vaccines' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-calendar-check w-5"></i> Vaccinations
            </button>
            <button onClick={() => setActiveTab('medical')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'medical' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className="fas fa-file-medical w-5"></i> Medical History
            </button>
            <button onClick={() => setActiveTab('setup')} className={`flex items-center gap-3 px-4 py-3 rounded-xl transition-all ${activeTab === 'setup' ? 'bg-indigo-50 text-indigo-600 font-bold' : 'text-slate-500 hover:bg-slate-50'}`}>
              <i className={`fas ${getPetIcon(pet.type, pet.breed)} w-5`}></i> Pet Profile
            </button>
            <button onClick={handleLogout} className="flex items-center gap-3 px-4 py-3 rounded-xl text-slate-500 hover:bg-rose-50 hover:text-rose-600 transition-all text-left w-full mt-2 border-t border-slate-50 pt-4">
              <i className="fas fa-sign-out-alt w-5"></i> Logout
            </button>
            {notifications.length > 0 && (
              <div className="mt-4 p-4 bg-amber-50 rounded-2xl border border-amber-100 animate-pulse">
                <div className="flex items-center justify-between mb-2">
                  <p className="text-[10px] font-black uppercase tracking-widest text-amber-600">
                    <i className="fas fa-bell mr-1"></i> {notifications.length} Alerts
                  </p>
                </div>
                <div className="space-y-2">
                  {notifications.map(n => (
                    <p key={n.id} className="text-[10px] text-amber-800 font-bold leading-tight">
                      • {n.message}
                    </p>
                  ))}
                </div>
              </div>
            )}
          </div>
        )}

        <div className="mt-auto pt-6 border-t border-slate-100">
          <div className="flex items-center gap-3 p-3 bg-slate-50 rounded-2xl border border-slate-100">
            <img src={pet.image || `https://picsum.photos/seed/${pet.id}/100`} alt={pet.name} className="w-10 h-10 rounded-full border-2 border-white shadow-sm object-cover" />
            <div className="flex-1 min-w-0">
              <p className="text-sm font-bold text-slate-800 truncate">{pet.name}</p>
              <p className="text-xs text-slate-500 truncate">{pet.breed}</p>
            </div>
            <button onClick={handleLogout} className="text-slate-400 hover:text-rose-600 transition-colors">
              <i className="fas fa-sign-out-alt"></i>
            </button>
          </div>
        </div>
      </nav>

      <main className="flex-1 md:ml-64 p-4 md:p-10 bg-slate-50 min-h-screen">
        <header className="mb-8">
          <h1 className="text-3xl font-black text-slate-800 tracking-tight">
            {currentTab === 'dashboard' ? `How's ${pet.name} doing?` : 
             currentTab === 'chat' ? 'Health AI Assistant' : 
             currentTab === 'tools' ? 'Pet AI Tools' :
             currentTab === 'training' ? 'Training Tips' :
             currentTab === 'setup' ? 'Setup Pet Profile' :
             currentTab === 'vaccines' ? 'Vaccination Center' :
             'Medical History'}
          </h1>
          <p className="text-slate-500 text-sm mt-1">
            {currentTab === 'tools' ? 'Advanced AI analysis for mood and behavior.' : 
             currentTab === 'training' ? `Expert techniques tailored for ${pet.breed}s.` :
             currentTab === 'medical' ? 'Keep track of clinical visits, surgeries, and conditions.' :
             currentTab === 'vaccines' ? 'Manage your pet immunization schedule and reminders.' :
             `Personalized care tracking for your ${pet.breed} ${pet.type}.`}
          </p>
        </header>

        {currentTab === 'dashboard' && <Dashboard pet={pet} onUpdatePet={handleUpdatePet} />}
        {currentTab === 'chat' && <AIChat pet={pet} onUpdatePet={handleUpdatePet} />}
        {currentTab === 'tools' && <PetAITools pet={pet} onUpdatePet={handleUpdatePet} />}
        {currentTab === 'training' && <TrainingTips pet={pet} />}
        {currentTab === 'setup' && <PetSetup pet={pet} onUpdate={handleUpdatePet} onComplete={() => setActiveTab('dashboard')} />}
        {currentTab === 'medical' && (
          <div className="space-y-6">
            <div className="bg-white p-8 rounded-[2rem] shadow-sm border border-slate-100">
              <h3 className="text-xl font-black text-slate-800 mb-6 flex items-center gap-2">
                <i className="fas fa-file-medical text-rose-500"></i> New Medical Record
              </h3>
              <form onSubmit={handleAddMedicalRecord} className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
                <div className="lg:col-span-2">
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Title / Visit Reason</label>
                  <input
                    type="text"
                    placeholder="e.g. Annual Checkup"
                    value={newRecordTitle}
                    onChange={(e) => setNewRecordTitle(e.target.value)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-rose-500 outline-none transition-all font-bold"
                  />
                </div>
                <div>
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Date</label>
                  <input
                    type="date"
                    value={newRecordDate}
                    onChange={(e) => setNewRecordDate(e.target.value)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-rose-500 outline-none transition-all font-bold"
                  />
                </div>
                <div>
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Report Type</label>
                  <select 
                    value={newRecordType}
                    onChange={(e) => setNewRecordType(e.target.value as any)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-rose-500 outline-none transition-all font-bold"
                  >
                    <option value="Checkup">Checkup</option>
                    <option value="Surgery">Surgery</option>
                    <option value="Injury">Injury</option>
                    <option value="Medication">Medication</option>
                    <option value="Other">Other</option>
                  </select>
                </div>
                <div className="lg:col-span-3">
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Description / Notes</label>
                  <textarea
                    placeholder="Details about the visit, diagnosis, or prescribed meds..."
                    value={newRecordDesc}
                    onChange={(e) => setNewRecordDesc(e.target.value)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-rose-500 outline-none transition-all font-medium h-12"
                  />
                </div>
                <div className="flex items-end">
                  <button className="w-full py-4 bg-slate-900 text-white rounded-xl font-black text-xs uppercase tracking-widest hover:bg-rose-600 transition-all shadow-lg active:scale-95">
                    Save Record
                  </button>
                </div>
              </form>
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
              {(!pet.medicalRecords || pet.medicalRecords.length === 0) ? (
                <div className="col-span-full py-20 text-center bg-white rounded-[2rem] border border-dashed border-slate-200">
                  <div className="w-16 h-16 bg-slate-50 rounded-full flex items-center justify-center mx-auto mb-4 text-slate-300">
                    <i className="fas fa-folder-open text-2xl"></i>
                  </div>
                  <p className="text-slate-400 font-medium italic">No clinical records found.</p>
                </div>
              ) : (
                pet.medicalRecords.map((record) => (
                  <div key={record.id} className="bg-white p-6 rounded-[2rem] shadow-sm border border-slate-100 hover:border-rose-200 transition-all group relative">
                    <button 
                      onClick={() => {
                        if (confirm('Delete this record?')) {
                          const updated = pet.medicalRecords.filter(r => r.id !== record.id);
                          handleUpdatePet({ ...pet, medicalRecords: updated });
                        }
                      }}
                      className="absolute top-4 right-4 text-slate-300 hover:text-rose-500 opacity-0 group-hover:opacity-100 transition-all"
                    >
                      <i className="fas fa-trash-can"></i>
                    </button>
                    <div className="flex items-center gap-4 mb-4">
                      <div className={`w-12 h-12 rounded-2xl flex items-center justify-center ${
                        record.type === 'Surgery' ? 'bg-rose-100 text-rose-600' :
                        record.type === 'Injury' ? 'bg-amber-100 text-amber-600' :
                        record.type === 'Medication' ? 'bg-emerald-100 text-emerald-600' :
                        'bg-indigo-100 text-indigo-600'
                      }`}>
                        <i className={`fas ${
                          record.type === 'Surgery' ? 'fa-heart-pulse' :
                          record.type === 'Injury' ? 'fa-bandage' :
                          record.type === 'Medication' ? 'fa-pills' :
                          'fa-stethoscope'
                        } text-xl`}></i>
                      </div>
                      <div>
                        <h4 className="font-black text-slate-800 leading-tight">{record.title}</h4>
                        <span className="text-[10px] font-black text-slate-400 uppercase tracking-widest">{record.type} • {new Date(record.date).toLocaleDateString('en-GB')}</span>
                      </div>
                    </div>
                    <p className="text-sm text-slate-500 italic line-clamp-3">"{record.description || 'No description provided.'}"</p>
                  </div>
                ))
              )}
            </div>
          </div>
        )}
        {currentTab === 'vaccines' && (
          <div className="space-y-6">
            <div className="bg-white p-8 rounded-[2rem] shadow-sm border border-slate-100">
              <h3 className="text-xl font-black text-slate-800 mb-6 flex items-center gap-2">
                <i className="fas fa-plus-circle text-indigo-600"></i> Add New Treatment
              </h3>
              <form onSubmit={handleAddVaccine} className="grid grid-cols-1 md:grid-cols-3 gap-4">
                <div className="md:col-span-1">
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Treatment Name</label>
                  <input
                    type="text"
                    placeholder="e.g. Rabies Booster"
                    value={newVaxName}
                    onChange={(e) => setNewVaxName(e.target.value)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-indigo-500 outline-none transition-all font-bold"
                  />
                </div>
                <div className="md:col-span-1">
                  <label className="block text-[10px] font-black uppercase tracking-widest text-slate-400 mb-2 ml-1">Due Date</label>
                  <input
                    type="date"
                    value={newVaxDate}
                    onChange={(e) => setNewVaxDate(e.target.value)}
                    className="w-full px-4 py-3 bg-slate-50 border border-slate-100 rounded-xl focus:ring-2 focus:ring-indigo-500 outline-none transition-all font-bold"
                  />
                </div>
                <div className="flex items-end">
                  <button className="w-full py-3 bg-indigo-600 text-white rounded-xl font-black text-xs uppercase tracking-widest hover:bg-slate-900 transition-all shadow-lg">
                    Add Record
                  </button>
                </div>
              </form>
            </div>

            <div className="bg-white rounded-3xl shadow-sm border border-slate-100 overflow-hidden">
              <div className="p-8 border-b border-slate-100 bg-slate-50/50 flex justify-between items-center">
                <h3 className="font-black text-slate-800 text-xl tracking-tight">Upcoming Treatments</h3>
                <div className="bg-indigo-100 text-indigo-700 px-4 py-1 rounded-full font-black text-xs uppercase">
                  {pet.vaccinations.filter(v => v.completedDate).length}/{pet.vaccinations.length} Done
                </div>
              </div>
              <div className="divide-y divide-slate-100">
                {pet.vaccinations.length === 0 ? (
                  <div className="p-12 text-center">
                    <div className="w-16 h-16 bg-slate-50 rounded-full flex items-center justify-center mx-auto mb-4 text-slate-300">
                      <i className="fas fa-notes-medical text-2xl"></i>
                    </div>
                    <p className="text-slate-400 font-medium italic">No medical records logged yet.</p>
                  </div>
                ) : (
                  pet.vaccinations.map((v) => {
                    const daysLeft = calculateDaysLeft(v.dueDate);
                    return (
                      <div key={v.id} className="p-8 flex items-center justify-between hover:bg-slate-50 transition-all">
                        <div className="flex items-center gap-6">
                          <div className={`w-14 h-14 rounded-2xl flex items-center justify-center ${v.completedDate ? 'bg-emerald-100 text-emerald-600' : 'bg-amber-100 text-amber-600'}`}>
                            <i className={`fas ${v.completedDate ? 'fa-check-double' : 'fa-syringe'} text-2xl`}></i>
                          </div>
                          <div>
                            <h4 className="text-lg font-black text-slate-800">{v.name}</h4>
                            <p className="text-slate-500 font-medium">
                              {v.completedDate ? `Completed on ${v.completedDate}` : `Due by ${v.dueDate}`}
                            </p>
                            {!v.completedDate && (
                              <div className="mt-2 flex items-center gap-2">
                                <span className={`px-3 py-1 rounded-full text-[10px] font-black uppercase tracking-widest ${
                                  daysLeft < 0 ? 'bg-rose-100 text-rose-600' : 
                                  daysLeft <= 7 ? 'bg-amber-100 text-amber-600 animate-pulse' : 
                                  'bg-indigo-100 text-indigo-600'
                                }`}>
                                  {daysLeft < 0 ? `Overdue by ${Math.abs(daysLeft)} days` : 
                                   daysLeft === 0 ? 'Due Today!' :                                    `${daysLeft} Days Remaining`}
                                </span>
                              </div>
                            )}
                          </div>
                        </div>
                        <div className="flex items-center gap-3">
                          <button onClick={() => toggleVaccine(v.id)} className={`px-6 py-3 rounded-full text-xs font-black uppercase tracking-widest transition-all ${v.completedDate ? 'bg-slate-100 text-slate-400 hover:bg-rose-50 hover:text-rose-500' : 'bg-slate-900 text-white hover:bg-indigo-600'}`}>
                            {v.completedDate ? 'Unmark' : 'Complete'}
                          </button>
                          <button 
                            onClick={() => {
                              if (confirm('Delete this record?')) {
                                const updatedVaccinations = pet.vaccinations.filter(vac => vac.id !== v.id);
                                handleUpdatePet({ ...pet, vaccinations: updatedVaccinations });
                              }
                            }}
                            className="w-10 h-10 rounded-full bg-slate-100 text-slate-400 hover:bg-rose-100 hover:text-rose-600 transition-all flex items-center justify-center"
                            title="Delete Record"
                          >
                            <i className="fas fa-trash-can text-xs"></i>
                          </button>
                        </div>
                      </div>
                    );
                  })
                )}
              </div>
            </div>
          </div>
        )}
      </main>
    </div>
  );
};

export default App;
